const assert = require('node:assert/strict');
const { buildSync } = require('esbuild');
const Module = require('node:module');
const bundle = buildSync({entryPoints:['client/keybinds.js'],bundle:true,platform:'node',format:'cjs',write:false}).outputFiles[0].text;
const compiled = new Module(__filename);compiled._compile(bundle,__filename);
const keys=compiled.exports;
const event = (key,extra={}) => ({key,ctrlKey:false,metaKey:false,altKey:false,shiftKey:false,defaultPrevented:false,...extra});
assert.equal(keys.matchesKeybind('global.settings',event(',',{ctrlKey:true})),true);
assert.equal(keys.matchesKeybind('global.settings',event(',',{metaKey:true})),true);
assert.equal(keys.matchesKeybind('global.settings',event(',',{ctrlKey:true,altKey:true})),false);
assert.equal(keys.matchesKeybind('global.settings',event(',',{ctrlKey:true,defaultPrevented:true})),false);
assert.equal(keys.matchesKeybind('global.settings',event(',',{ctrlKey:true,isComposing:true})),false);
assert.equal(keys.matchesKeybind('global.terminal',event('~',{ctrlKey:true,shiftKey:true,code:'Backquote'})),true);
assert.equal(keys.matchesKeybind('image.zoomIn',event('+',{shiftKey:true})),true);
assert.equal(keys.matchesKeybind('video.play',event(' ')),true);
assert.equal(keys.matchesKeybind('files.refresh',event('F5',{ctrlKey:true})),false);
assert.equal(keys.normalizeKeybind('Control+Shift+Z'),'Ctrl+Shift+z');
assert.equal(keys.normalizeKeybind('Ctrl+Alt+Meta+Shift+k'),'Ctrl+Meta+Alt+Shift+k');
assert.equal(keys.keybindFromEvent(event('Control',{ctrlKey:true})),null);
assert.equal(keys.normalizeKeybind('Hyper+x'),null);
assert.equal(keys.normalizeKeybind('NotAKey'),null);
keys.setKeybinds({'global.settings':['Alt+s'],'files.refresh':[], 'video.play':['Shift+?'],'future.panel':['Alt+F9'],constructor:['Ctrl+a'],'global.files':['NotAKey']});
assert.equal(keys.matchesKeybind('global.settings',event(',',{ctrlKey:true})),false);
assert.equal(keys.matchesKeybind('global.settings',event('s',{altKey:true})),true);
assert.equal(keys.matchesKeybind('files.refresh',event('F5')),false);
assert.equal(keys.matchesKeybind('global.files',event('E',{ctrlKey:true,shiftKey:true})),true,'Invalid override uses baseline');
assert.deepEqual(keys.getKeybinds()['future.panel'],['Alt+F9']);
assert.equal(keys.keybindConflict('global.keybinds',['Alt+s']).id,'global.settings');
assert.equal(keys.keybindConflict('files.copy',['Mod+v']).id,'files.paste');
assert.equal(keys.keybindConflict('image.reset',['ArrowLeft']).id,'image.left');
assert.equal(keys.keybindConflict('video.fullscreen',['Mod+l']),undefined,'Different panel scopes may share a stroke');
const copy=keys.getKeybinds();copy['global.settings'].push('F2');assert.deepEqual(keys.getKeybinds()['global.settings'],['Alt+s']);
keys.setKeybinds(null);assert.deepEqual(keys.getKeybinds(),{});
assert.equal(keys.normalizeKeybind('Alt+MouseLeft'),'Alt+MouseLeft');
assert.equal(keys.pointerKeybindFromEvent(event('',{button:2,altKey:true})),'Alt+MouseRight');
assert.equal(keys.matchesPointerKeybind('cad.panMouse',event('',{button:2})),true);
assert.equal(keys.matchesPointerKeybind('cad.panMouse',event('',{button:2,shiftKey:true})),false);
assert.equal(keys.matchesModifierKeybind('cad.fast',event('w',{shiftKey:true})),true);
keys.setKeybinds({'cad.orbitMouse':['Shift+MouseLeft'],'cad.panMouse':['Alt+MouseLeft'],'cad.fast':['Alt'],'cad.slow':[]});
assert.equal(keys.matchesPointerKeybind('cad.orbitMouse',event('',{button:0,shiftKey:true})),true);
assert.equal(keys.matchesPointerKeybind('cad.orbitMouse',event('',{button:0})),false);
assert.equal(keys.matchesModifierKeybind('cad.fast',event('w',{altKey:true})),true);
assert.equal(keys.matchesModifierKeybind('cad.fast',event('w',{shiftKey:true})),false);
assert.equal(keys.matchesModifierKeybind('cad.slow',event('w',{ctrlKey:true})),false);
assert.equal(keys.keybindConflict('cad.orbitMouse',['Alt+MouseLeft']).id,'cad.panMouse');
keys.setKeybinds({});
console.log('Keybind defaults, rebinding, disabling, modifiers, input bounds, unknown-ID preservation and conflicts passed.');
