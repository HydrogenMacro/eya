const assert = require('node:assert/strict');
const path = require('node:path');
const { chromium } = require('playwright');
const { buildSync } = require('esbuild');
(async () => {
  const bundle = buildSync({ entryPoints: [path.resolve('client/browser-panel.js')], bundle: true, platform: 'browser', format: 'iife', globalName: 'EyaBrowser', write: false }).outputFiles[0].text;
  const browser = await chromium.launch({ headless: true, args: process.env.EYA_BROWSER_NO_SANDBOX ? ['--no-sandbox'] : [] });
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 700 }, isMobile: true, hasTouch: true });
    await page.goto('about:blank'); await page.addScriptTag({ content: bundle });
    await page.evaluate(() => {
      window.navigations = []; window.activations = 0; window.startAttempts = 0; window.resizes = []; window.inputs = [];
      window.panel = EyaBrowser.createBrowserPanel({ request: async () => { throw Error('unexpected proxy request'); }, openRemoteBrowser: async () => ({ ready: true, start() { if (++window.startAttempts === 1) return Promise.reject(Error('Chromium could not start')); return new Promise(resolve => { window.finishStartup = resolve; }); }, privacy() {}, resize(w, h) { window.resizes.push([w, h]); }, input(value) { window.inputs.push(value); }, insertText(text) { window.inputs.push({ text }); }, filters() { throw Error('filter sync must not block browsing'); }, async activateTab() { window.activations++; return {}; }, navigate(url) { window.navigations.push(url); }, closeTab() {}, close() {} }) });
      document.body.append(window.panel.element); window.panel.element.style.cssText = 'height:650px;width:100%';
    });
    await page.getByLabel('Address or search').fill('https://example.test/'); await page.getByLabel('Address or search').press('Enter');
    await page.getByText('Chromium could not start').waitFor();
    assert.equal(await page.evaluate(() => window.activations), 0, 'failed startup must not activate a tab');
    await page.getByLabel('Address or search').press('Enter');
    await page.waitForFunction(() => typeof window.finishStartup === 'function');
    assert.equal(await page.evaluate(() => window.activations), 0, 'tab activation must wait for Chromium readiness');
    await page.evaluate(() => window.finishStartup());
    await page.waitForFunction(() => window.navigations.includes('https://example.test/'));
    const toolbar = await page.locator('.eya-browser-toolbar').evaluate(el => ({ width: el.clientWidth, scroll: el.scrollWidth, heights: [...el.children].filter(e => e.offsetWidth).map(e => e.getBoundingClientRect().top) }));
    assert.ok(toolbar.scroll <= toolbar.width, 'toolbar must fit on one row');
    assert.ok(Math.max(...toolbar.heights) - Math.min(...toolbar.heights) < 10, 'toolbar controls must share a row');
    await page.getByLabel('Browser options').click();
    await page.getByTitle('Zoom in').click();
    assert.equal(await page.getByTitle('Reset zoom').textContent(), 'Zoom 110%');
    assert.ok(await page.evaluate(() => window.resizes.length > 0), 'zoom must update the remote viewport');
    await page.getByTitle('Toggle fullscreen').click();
    await page.waitForFunction(() => document.fullscreenElement === window.panel.element);
    await page.evaluate(() => document.exitFullscreen());
    await page.evaluate(() => { window.resizes = []; window.panel.element.style.height = '480px'; });
    await page.waitForFunction(() => window.resizes.length > 0);
    assert.equal(await page.locator('.eya-browser-text-surface').getAttribute('inputmode'), 'none');
    await page.evaluate(() => {
      window.keyboardShowCalls = 0;
      Object.defineProperty(navigator, 'virtualKeyboard', { configurable: true, value: { show() { window.keyboardShowCalls++; window.keyboardGesture = navigator.userActivation.isActive; } } });
      const button = document.createElement('button'); button.id = 'activate-test-keyboard'; button.textContent = 'Activate keyboard';
      button.addEventListener('pointerdown', event => event.preventDefault());
      button.addEventListener('click', () => window.panel.api.activateKeyboard());
      document.body.append(button);
    });
    await page.locator('#activate-test-keyboard').tap();
    assert.equal(await page.locator('.eya-browser-text-surface').getAttribute('inputmode'), 'text');
    assert.ok(await page.locator('.eya-browser-text-surface').evaluate(el => el === document.activeElement), 'activation focuses the native input');
    assert.equal(await page.evaluate(() => window.keyboardShowCalls), 1, 'activation requests the virtual keyboard');
    assert.equal(await page.evaluate(() => window.keyboardGesture), true, 'keyboard request retains user activation');
    await page.evaluate(() => window.panel.api.dismissKeyboard());
    assert.equal(await page.locator('.eya-browser-text-surface').getAttribute('inputmode'), 'none');
    await page.locator('.eya-browser-text-surface').focus();
    await page.keyboard.press('Control+f');
    await page.keyboard.type('a');
    assert.equal(await page.evaluate(() => window.inputs.some(input => input.key === 'f' && input.modifiers & 2)), false, 'Configured Find shortcut is consumed before remote forwarding');
    assert.equal(await page.getByLabel('Find text in the current page').inputValue(), 'a');
    await page.keyboard.press('Escape'); await page.locator('.eya-browser-text-surface').focus(); await page.keyboard.type('a');
    assert.ok(await page.evaluate(() => window.inputs.some(input => input.key === 'a' && input.action === 'keyDown')), 'page receives printable keydown');
    assert.ok(await page.evaluate(() => window.inputs.some(input => input.text === 'a')), 'page receives typed text');
    assert.equal(await page.getByLabel('Browser tabs').textContent(), '1');
    const countLayout = await page.locator('.eya-browser-tab-count').evaluate(el => {
      const inner = el.getBoundingClientRect(), outer = el.parentElement.getBoundingClientRect(), style = getComputedStyle(el);
      return { centeredX: Math.abs((inner.left + inner.right - outer.left - outer.right) / 2), centeredY: Math.abs((inner.top + inner.bottom - outer.top - outer.bottom) / 2), border: parseFloat(style.borderTopWidth), radius: parseFloat(style.borderTopLeftRadius) };
    });
    assert.ok(countLayout.centeredX < 1 && countLayout.centeredY < 1 && countLayout.border > 0 && countLayout.radius > 0, 'tab count is centered in a rounded square icon');
    assert.equal(await page.getByTitle('Navigate').count(), 0);
    await page.getByLabel('Browser tabs').click();
    assert.equal(await page.getByRole('button', { name: 'New tab', exact: true }).count(), 1);
    await page.getByRole('button', { name: 'New tab', exact: true }).click();
    assert.equal(await page.locator('.eya-browser-tab').count(), 2);
    assert.equal(await page.getByLabel('Browser tabs').textContent(), '2');
    await page.locator('.eya-browser-tab-close').last().click();
    assert.equal(await page.locator('.eya-browser-tab').count(), 1);
    assert.equal(await page.getByTitle('Toggle developer tools').count(), 0);
    assert.equal(await page.locator('.eya-browser-bookmarks').count(), 0);
    await page.evaluate(() => window.panel.onClose());
    console.log('Mobile browser navigation and tab menu passed.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
