const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const { buildSync } = require('esbuild');

(async () => {
  const code = buildSync({ entryPoints: ['client/video-controls.js'], bundle: true, platform: 'browser', format: 'iife', globalName: 'VideoControls', write: false }).outputFiles[0].text;
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 375, height: 667 }, isMobile: true, hasTouch: true });
    await page.goto('about:blank');
    await page.evaluate(() => { const meta = document.createElement('meta'); meta.name = 'viewport'; meta.content = 'width=device-width, initial-scale=1'; document.head.append(meta); });
    await page.addScriptTag({ content: code });
    await page.evaluate(() => {
      const video = document.createElement('video');
      window.player = VideoControls.createVideoControls(video);
      window.video = video;
      document.body.append(window.player.element);
      const track = video.addTextTrack('subtitles', 'English', 'en');
      track.addCue(new VTTCue(0, 10, 'Hello <world>'));
    });
    await page.evaluate(() => { window.player.element.style.height = '580px'; });
    const menu = page.locator('.eya-video-settings');
    const back = name => page.getByRole('button', { name: 'Back to ' + name, exact: true }).click();
    await page.getByRole('button', { name: 'Settings', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Subtitles', exact: true }).click();
    await page.getByRole('menuitemradio', { name: 'English', exact: true }).click();
    assert.equal(await page.evaluate(() => window.video.textTracks[0].mode), 'hidden');
    await back('Settings');
    await page.getByRole('menuitem', { name: 'Playback', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Playback speed' }).click();
    await page.getByRole('menuitemradio', { name: '1.5×', exact: true }).click();
    await page.getByRole('menuitemcheckbox', { name: 'Loop video' }).click();
    await back('Settings');
    await page.getByRole('menuitem', { name: 'Subtitle appearance', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Subtitle position', exact: true }).click();
    await page.getByRole('menuitemradio', { name: 'Top', exact: true }).click();
    assert.equal(await page.evaluate(() => window.video.playbackRate), 1.5);
    assert.equal(await page.evaluate(() => window.video.loop), true);
    assert.equal(await page.locator('.eya-video-captions').evaluate(el => el.style.top), '6%');
    assert.equal(await page.locator('.eya-video-stage').evaluate(el => getComputedStyle(el).touchAction), 'pan-y');
    assert.equal(await menu.locator('select,input[type=color]').count(), 0);
    assert.notEqual(await menu.evaluate(el => getComputedStyle(el).backdropFilter), 'none');
    await back('Settings');
    await page.getByRole('menuitem', { name: 'Subtitles', exact: true }).click();
    await page.getByRole('menuitem', { name: 'How to embed subtitles' }).click();
    assert.match(await page.locator('.eya-video-help pre').textContent(), /ffmpeg .*mov_text/);
    await page.getByRole('button', { name: 'Close', exact: true }).click();
    assert.equal(await menu.isVisible(), true, 'closing help should preserve the settings menu');
    assert.equal(await page.evaluate(() => window.video.playsInline), true);
    assert.equal(await page.locator('input[type=file]').count(), 0);
    await page.getByRole('button', { name: 'Settings', exact: true }).click();
    await page.getByRole('button', { name: 'Fullscreen', exact: true }).click();
    await page.waitForFunction(() => document.fullscreenElement === window.player.element);
    await page.getByRole('button', { name: 'Settings', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Subtitle appearance', exact: true }).click();
    await menu.evaluate(el => { el.scrollTop = el.scrollHeight; });
    await page.getByRole('menuitem', { name: 'Subtitle position', exact: true }).click();
    await page.getByRole('menuitemradio', { name: 'Bottom', exact: true }).click();
    assert.equal(await page.evaluate(() => document.fullscreenElement === window.player.element), true);
    await page.getByRole('button', { name: 'Settings', exact: true }).click();
    await page.getByRole('button', { name: 'Exit fullscreen', exact: true }).click();
    await page.waitForFunction(() => !document.fullscreenElement);
    // Isolate the UI state machine from decoder availability.
    await page.evaluate(() => {
      let paused = true;
      Object.defineProperty(window.video, 'paused', { get: () => paused });
      window.video.play = () => { paused = false; window.video.dispatchEvent(new Event('play')); return Promise.resolve(); };
      window.video.pause = () => { paused = true; window.video.dispatchEvent(new Event('pause')); };
    });
    await page.getByRole('button', { name: 'Play video', exact: true }).tap();
    await page.getByRole('button', { name: 'Pause video', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Pause video', exact: true }).tap();
    assert.equal(await page.evaluate(() => window.video.paused), true);
    await page.evaluate(() => { const outside = document.createElement('button'); outside.textContent = 'Outside'; document.body.append(outside); });
    await page.getByRole('button', { name: 'Outside', exact: true }).tap();
    assert.equal(await page.locator('.eya-video-player').evaluate(el => el.classList.contains('eya-video-ui-hidden')), true);
    await page.locator('.eya-video-stage').tap({ position: { x: 20, y: 20 } });
    await page.getByRole('button', { name: 'Play video', exact: true }).waitFor();
    assert.equal(await page.evaluate(() => window.video.paused), true, 'revealing controls should not start playback');
    await page.locator('.eya-video-stage').tap({ position: { x: 20, y: 20 } });
    assert.equal(await page.evaluate(() => window.video.paused), true, 'background tap must never change playback');
    await page.locator('.eya-video-stage').tap({ position: { x: 20, y: 20 } });
    await page.getByRole('button', { name: 'Play video', exact: true }).tap();
    await page.waitForFunction(() => window.player.element.classList.contains('eya-video-ui-hidden'), null, { timeout: 5000 });
    await page.evaluate(() => { window.player.element.style.height = '300px'; document.body.style.height = '2000px'; window.scrollTo(0, 0); });
    const cdp = await page.context().newCDPSession(page);
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 30, y: 200 }] });
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 30, y: 80 }] });
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
    await page.waitForFunction(() => window.scrollY > 0, null, { timeout: 5000 });
    await cdp.detach();
    await page.evaluate(() => window.player.dispose());
    console.log('Video controls and subtitle selection passed.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
