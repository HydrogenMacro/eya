const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { fixture, KEY } = require('./continuity-fixture.cjs');

(async () => {
  const f = await fixture();
  try {
    const page = await f.client({ connect: false });
    assert.equal(await page.locator('#connect-dialog #default-command').count(), 0);
    await page.locator('#url').fill(f.http);
    await page.locator('#key').fill('incorrect');
    await page.locator('#toggle-password').click();
    assert.equal(await page.locator('#key').getAttribute('type'), 'text');
    await page.locator('#toggle-password').click();
    await page.waitForFunction(() => !document.querySelector('#connection-spinner').hidden);
    await page.waitForFunction(() => /password/i.test(document.querySelector('#dialog-error').textContent));
    assert.equal(await page.locator('#connect-dialog').isVisible(), true);
    assert.equal(await page.evaluate(() => EyaWorkspaces.getState().workspace), null);
    await page.locator('#key').fill(KEY);
    await page.waitForFunction(() => document.querySelector('#status').dataset.connected === 'true');
    assert.equal(await page.locator('#connect-dialog').isVisible(), false);
    await page.waitForFunction(() => /^\d+ ms$/.test(document.querySelector('#latency').textContent));
    assert.equal(await page.locator('#status').textContent(), '');

    await page.keyboard.press('Control+,');
    await page.locator('#settings-dialog').waitFor();
    assert.equal(await page.locator('#settings-dialog [data-settings]:visible').count(), 0);
    assert.equal(await page.locator('#settings-dialog #client-update-check').count(), 0);
    await page.getByRole('button', { name: 'Browser', exact: true }).click();
    await page.selectOption('#browser-resolution', '1280');
    await page.selectOption('#browser-quality', '60');
    await page.getByRole('button', { name: 'Back', exact: true }).click();
    await page.getByRole('button', { name: 'Task Manager', exact: true }).click();
    await page.selectOption('#task-interval', '250');
    await page.check('#task-tree');
    await page.getByRole('button', { name: 'Back', exact: true }).click();
    await page.getByRole('button', { name: 'Terminal', exact: true }).click();
    await page.locator('#default-command').fill('printf settings-startup');
    await page.locator('#settings-search').fill('subtitle');
    assert.equal(await page.locator('[data-settings-group=video]').isVisible(), true);
    await page.screenshot({ path: '/tmp/eya-settings-search.png' });
    await page.getByRole('button', { name: 'Back', exact: true }).click();
    await page.screenshot({ path: '/tmp/eya-settings-home.png' });
    await page.locator('#close-settings').click();

    const task = await page.evaluate(() => EyaPanels.create('task-manager'));
    const state = await page.evaluate(id => EyaPanels.call(id, 'getSettings'), task);
    assert.equal(state.interval, 250); assert.equal(state.tree, true);
    await page.keyboard.press('Control+,');
    await page.getByRole('button', { name: 'Task Manager', exact: true }).first().click();
    await page.selectOption('#task-interval', '1000');
    assert.equal(await page.evaluate(id => EyaPanels.call(id, 'getSettings').interval, task), 1000);
    await page.locator('#close-settings').click();
    const browser = await page.evaluate(() => EyaPanels.create('web-browser'));
    assert.equal(await page.evaluate(id => EyaPanels.call(id, 'getSettings').stream.resolution, browser), '1280');
    assert.equal(await page.evaluate(id => EyaPanels.call(id, 'getSettings').stream.quality, browser), 60);
    await page.getByRole('button', { name: 'Workspace menu', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Client updates', exact: true }).click();
    assert.equal(await page.locator('#updates-dialog').isVisible(), true);
    await page.locator('#close-updates').click();
    await page.evaluate(file => EyaPanels.openFile(file), path.join(f.files, 'seed.txt'));
    await page.locator('.cm-content').click(); await page.keyboard.press('Control+End'); await page.keyboard.type('edited');
    await page.keyboard.press('Control+z'); assert.equal((await page.locator('.cm-content').innerText()).includes('edited'), false);
    await page.keyboard.press('Control+Shift+z'); assert.equal((await page.locator('.cm-content').innerText()).includes('edited'), true);
    await page.keyboard.press('Control+f'); await page.locator('.cm-search').waitFor(); await page.keyboard.press('Escape');
    await page.getByRole('button', { name: 'Workspace menu', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Keyboard shortcuts', exact: true }).click();
    await page.getByRole('searchbox', { name: 'Search shortcuts', exact: true }).fill('Save file');
    await page.getByRole('button', { name: 'Change Save file shortcut', exact: true }).click(); await page.keyboard.press('Control+Alt+s');
    await page.getByRole('button', { name: 'Close keyboard shortcuts', exact: true }).click();
    await page.locator('.cm-content').click(); await page.keyboard.press('Control+Alt+s');
    await page.locator('#file-status').filter({hasText:'seed.txt saved.'}).waitFor({state:'attached'});
    assert.match(await fs.readFile(path.join(f.files, 'seed.txt'), 'utf8'), /edited/);
    await f.named(page, 'Configured'); await f.saved(page);
    const record = await f.snapshot();
    const preferences = record.workspaces.find(value => value.name === 'Configured').preferences;
    assert.equal(preferences.browser.stream.resolution, '1280');
    assert.equal(preferences.taskManager.interval, 1000);
    assert.equal(preferences.defaultCommand, 'printf settings-startup');
    assert.deepEqual(preferences.keybinds['editor.save'], ['Ctrl+Alt+s']);
    await page.setViewportSize({ width: 360, height: 640 });
    await page.keyboard.press('Control+,');
    await page.screenshot({ path: '/tmp/eya-settings-mobile.png' });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    assert.deepEqual(f.errors, []);
    console.log('Settings/connection: automatic authentication, rejection, spinner, password visibility, submenus, panel defaults/live updates, saved preferences, navbar updates and mobile bounds passed');
  } finally { await f.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
